import fs from 'node:fs';
const root = new URL('../', import.meta.url);
const pins = fs.readFileSync(new URL('scripts/pins.mjs', root), 'utf8').replace('export const PINS', 'const PINS');
const source = fs.readFileSync(new URL('scripts/bootstrap.mjs', root), 'utf8')
  .replace("import { PINS } from './pins.mjs';\n", '')
  .replace(/\n\/\/ The generated self-contained installer[\s\S]*$/, '');
const classifier = fs.readFileSync(new URL('extensions/classifier-model.ts', root), 'utf8');
const text = '#!/usr/bin/env bash\n# Generated by scripts/build-installer.mjs; edit the source modules.\nset -euo pipefail\nnode --input-type=module - "$@" <<\'BOOTSTRAP_ENGINE\'\n' + pins + source +
  '\nconst CLASSIFIER_SOURCE = ' + JSON.stringify(classifier) + ';\n' +
  'main(CLASSIFIER_SOURCE).catch(error => { console.error(error); process.exitCode = 1; });\nBOOTSTRAP_ENGINE\n';
const dest = new URL('install.sh', root);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(dest, 'utf8') !== text) throw Error('generated installer is out of sync');
  console.log('Installer engine, pins and embedded classifier are in sync');
} else fs.writeFileSync(dest, text, { mode: 0o755 });
